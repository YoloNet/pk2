    /** Decode avatar untuk nama bot; null jika nama tiada imej atau decode gagal. */
    fun bitmapFor(name: String): ImageBitmap? {
        val b64 = when (name) {
            "vic" -> VIC_B64
            "Masta" -> MASTA_B64
            "Ayam" -> AYAM_B64
            else -> return null
        }
        return try {
            val bytes = Base64.decode(b64, Base64.DEFAULT)
            val bmp = BitmapFactory.decodeByteArray(bytes, 0, bytes.size) ?: return null
            bmp.asImageBitmap()
        } catch (e: Exception) {
            null
        }
    }
}

/** Ingat bitmap avatar untuk nama bot; null jika tiada imej. */
@Composable
fun rememberAvatar(name: String): ImageBitmap? {
    return remember(name) { Avatars.bitmapFor(name) }
}
